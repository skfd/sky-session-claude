using System.Text.Json;
using SessionCore;

namespace SessionCore.Tests;

/// <summary>
/// Locks what <c>/clear</c> leaves behind, read off the two transcripts it touches.
///
/// <c>/clear</c> does not end the process. It queues itself in the old transcript, starts a
/// new session id in the same terminal, and copies the old <c>custom-title</c> into the top
/// of the new file. Before this, the old conversation kept whatever it last declared forever
/// (nothing would ever prompt it again to expire the claim), and the new one answered to a
/// name it never earned. The record shapes below are the ones Claude Code wrote on 2026-08-23
/// in ~/.claude/projects/C--Users-kk-Code-cowork (6fb91ffc… → b976a1c9…).
/// </summary>
public class ClearTests
{
    private static string J(string s) => JsonSerializer.Serialize(s);

    private static string Title(string t) =>
        "{\"type\":\"custom-title\",\"customTitle\":" + J(t) + ",\"sessionId\":\"x\"}";

    private static string User(string text, string uuid = "u1") =>
        "{\"type\":\"user\",\"uuid\":" + J(uuid) + ",\"message\":{\"role\":\"user\",\"content\":" + J(text)
        + "},\"origin\":{\"kind\":\"human\"}}";

    private static string Asst(string text) =>
        "{\"type\":\"assistant\",\"message\":{\"model\":\"claude-opus-5\",\"stop_reason\":\"end_turn\","
        + "\"content\":[{\"type\":\"text\",\"text\":" + J(text) + "}]}}";

    private static string Enqueue(string content) =>
        "{\"type\":\"queue-operation\",\"operation\":\"enqueue\",\"timestamp\":\"2026-08-23T04:12:48.263Z\","
        + "\"sessionId\":\"x\",\"content\":" + J(content) + "}";

    private const string Dequeue =
        "{\"type\":\"queue-operation\",\"operation\":\"dequeue\",\"timestamp\":\"2026-08-23T04:12:48.305Z\",\"sessionId\":\"x\"}";

    private static readonly string Caveat =
        User("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>", "c0");

    private static readonly string ClearCommand =
        User("<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>", "c1");

    private static SessionFileFields Parse(params string[] lines) => SessionFileParser.Parse(lines);

    // --- the conversation that was cleared -------------------------------------

    [Fact]
    public void A_transcript_whose_last_act_is_a_queued_clear_ended_by_clear()
    {
        var f = Parse(Title("Renderers"), User("do the thing"), Asst("Done. Want me to push?"),
            Enqueue("/clear"), Dequeue);

        Assert.True(f.EndedByClear);
    }

    [Fact]
    public void A_clear_queued_mid_turn_still_ends_it_once_the_reply_lands()
    {
        var f = Parse(User("do the thing"), Enqueue("/clear"), Asst("Done."), Dequeue);

        Assert.True(f.EndedByClear);
    }

    [Fact]
    public void A_prompt_after_the_clear_means_the_conversation_went_on()
    {
        // Resumed by id later and carried on: the clear is history, not the ending.
        var f = Parse(User("a"), Asst("b"), Enqueue("/clear"), Dequeue, User("back again", "u2"));

        Assert.False(f.EndedByClear);
    }

    [Fact]
    public void An_ordinary_queued_prompt_is_not_a_clear()
    {
        var f = Parse(User("a"), Enqueue("/clearly not a command"), Enqueue("tell me more"), Dequeue);

        Assert.False(f.EndedByClear);
    }

    // --- the conversation /clear opened -----------------------------------------

    [Fact]
    public void The_new_transcript_starts_by_clear_and_carries_the_old_title()
    {
        var f = Parse(Title("Renderers"), Caveat, ClearCommand);

        Assert.True(f.StartedByClear);
        Assert.Equal("Renderers", f.OpeningTitle);
        Assert.False(f.EndedByClear);
        Assert.Null(f.LastPromptUuid);   // the /clear record is harness noise, not a prompt
    }

    [Fact]
    public void A_clear_typed_mid_conversation_is_not_a_start()
    {
        var f = Parse(User("hello"), Asst("hi"), ClearCommand);

        Assert.False(f.StartedByClear);
    }

    [Fact]
    public void A_title_written_after_the_first_record_is_not_an_opening_title()
    {
        var f = Parse(User("hello"), Title("Fresh"));

        Assert.Null(f.OpeningTitle);
    }

    // --- rows and the fold -------------------------------------------------------

    private static SessionInfo Row(string dir, string id, params string[] lines)
    {
        var path = Path.Combine(dir, id + ".jsonl");
        File.WriteAllLines(path, lines);
        return new SessionScanner(dir).BuildRow(new FileInfo(path), SessionFileParser.DefaultContextWindow);
    }

    private static string TempDir()
    {
        var dir = Path.Combine(Path.GetTempPath(), "sky-clear-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(dir);
        return dir;
    }

    [Fact]
    public void A_cleared_conversation_is_not_unfinished_however_it_ended()
    {
        var dir = TempDir();
        try
        {
            var row = Row(dir, "old", User("do it"), Asst("Shall I push?"), Enqueue("/clear"), Dequeue);

            Assert.True(row.ClearedAway);
            Assert.False(row.Unfinished);
            Assert.Equal("", row.WaitingOn);
            Assert.Equal(SessionStatus.WaitingYou, row.Status);   // Law 1: the card still says what the file says
        }
        finally { Directory.Delete(dir, true); }
    }

    [Fact]
    public void An_inherited_title_is_flagged_until_something_renames_it()
    {
        var dir = TempDir();
        try
        {
            var inherited = Row(dir, "a", Title("Renderers"), Caveat, ClearCommand, User("next thing"));
            var renamed = Row(dir, "b", Title("Renderers"), Caveat, ClearCommand, User("next thing"), Title("Routers"));
            var plain = Row(dir, "c", Title("Renderers"), User("hello"));

            Assert.True(inherited.TitleInherited);
            Assert.False(renamed.TitleInherited);
            Assert.False(plain.TitleInherited);   // a --name launch, not a /clear
        }
        finally { Directory.Delete(dir, true); }
    }

    [Fact]
    public void The_fold_reads_a_cleared_conversation_as_quiet_over_a_stranded_claim()
    {
        var cleared = new SessionInfo
        {
            SessionId = "old",
            Cwd = @"C:\Users\kk\Code\demo",
            Status = SessionStatus.WaitingYou,
            LastPromptUuid = "u1",
            HasOperator = true,
            ClearedAway = true,
        };
        var stranded = new Declaration { State = Declared.Blocked, Note = "waiting on you", AtTurn = "u1" };

        Assert.Equal(ProjectState.Quiet, ProjectFold.Of(cleared, Disposition.None, stranded));

        var roll = Assert.Single(ProjectFold.Roll([cleared], declarationOf: _ => stranded));
        Assert.Equal(ProjectState.Quiet, roll.State);
        Assert.Equal(0, roll.Unfinished);
    }

    // --- the SessionStart hook -----------------------------------------------------

    [Fact]
    public void The_hook_speaks_only_after_a_clear()
    {
        var answer = ClearHook.Answer("""{"session_id":"n","source":"clear","hook_event_name":"SessionStart"}""");

        Assert.NotNull(answer);
        using var doc = JsonDocument.Parse(answer!);
        var output = doc.RootElement.GetProperty("hookSpecificOutput");
        Assert.Equal("SessionStart", output.GetProperty("hookEventName").GetString());
        Assert.Contains("/clear", output.GetProperty("additionalContext").GetString());
    }

    [Theory]
    [InlineData("""{"source":"startup"}""")]
    [InlineData("""{"source":"resume"}""")]
    [InlineData("""{"source":"compact"}""")]
    [InlineData("""{}""")]
    [InlineData("""[1,2]""")]
    [InlineData("not json")]
    [InlineData("")]
    [InlineData(null)]
    public void The_hook_is_silent_for_anything_else(string? stdin)
    {
        Assert.Null(ClearHook.Answer(stdin));
    }
}
